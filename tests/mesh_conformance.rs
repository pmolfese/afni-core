// Conformance of `afni_core::topology` and `afni_core::mesh` against SUMA:
// triangle areas, node areas, triangle and node normals, edge lists, and
// boundary nodes, as written by `SurfaceMetrics` and `SurfMeasures` for the
// committed meshes `irr2` (an irregular closed sphere) and `patch2` (an open
// piece of it). Generated by tests/data/regenerate_surface_refs.sh.
//
// SUMA computes in single precision and prints six decimals, so the tolerances
// below are those of the reference, not of afni-core.
