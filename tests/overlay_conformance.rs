// WHAT THIS FILE IS
//
// Conformance of `afni_core::overlay` against SUMA's own value-to-color mapping,
// as run by AFNI's `ScaleToMap` program (SUMA_ScaleToMap in SUMA_Color.c).
// tests/data/conformance/scaletomap.ref holds 54 cases (four color maps by
// interpolated, banded and direct mapping, intensity clipping, auto range, mask
// ranges, the brightness factor, and a zero-width range), generated by
// tests/data/regenerate_scaletomap.sh. Each case is replayed through
// `evaluate_rows` and compared node by node; a node `ScaleToMap` masked must be
// invisible here.
//
// With AFNI_CORE_LIVE=1 the cases are also re-run through the live program.
