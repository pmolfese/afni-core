// WHAT THIS FILE IS
//
// Conformance of `afni_core::stats` against AFNI's own statistical library
// (NIfTI `nifticdf.c`, the code `p2dsetstat`, `3dcalc` and friends use).
// Expected values live in tests/data/conformance/nifti_stats.ref, generated by
// tests/data/regenerate_nifti_stats.sh from AFNI's source at full precision.
// Also checks the older `cdf` program's two-sided conventions
// (conformance/cdf.ref) and, with AFNI_CORE_LIVE=1, the live `cdf`, `ccalc`
// and `p2dsetstat` programs.
//
// HOW IT RELATES TO THE REST OF THE CRATE
//
// Uses the shared harness in tests/common/mod.rs. Documents every place where
// afni-core deliberately differs from AFNI (see "KNOWN DEPARTURES" below).
//
// KNOWN DEPARTURES (intentional; each is also in the roadmap discovery log)
//
//  * Discrete distributions (binomial, Poisson): AFNI/CDFLIB evaluate a
//    continuous extension at non-integer statistics; afni-core uses the true
//    step function. Compared here only at integer statistics. Inverses are
//    integer quantiles, so they are not compared with AFNI's real-valued roots.
//  * AFNI's correl_p2t returns 0 when nort < 1; afni-core accepts nort >= 0.
//  * AFNI's CDFLIB inverse is only good to ~1e-8 absolute (for example
//    `-1 0.5 CORREL 18` gives -5.0e-9 where the exact answer is 0), so inverses
//    are compared with an absolute tolerance of 5e-8.
//  * AFNI's uniform q = 1 - u is outside [0, 1] when the statistic is outside
//    the support (e.g. 1.25); afni-core clamps to the valid probability.
//  * AFNI returns sentinels (0, -1, 99.99, 1.0) on error; afni-core errors.
// ---------------------------------------------------------------------------

mod common;

use afni_core::stat::{IntentOrigin, StatKind, StatSpec};
use afni_core::stats::{critical_value, p_value, Tail};
use common::{is_close, Fixture, Tolerance};

/// NIfTI intent names used in the fixture -> AFNI/NIfTI stat codes.
fn code_for(name: &str) -> i64 {
    match name {
        "CORREL" => 2,
        "TTEST" => 3,
        "FTEST" => 4,
        "ZSCORE" => 5,
        "CHISQ" => 6,
        "BETA" => 7,
        "BINOM" => 8,
        "GAMMA" => 9,
        "POISSON" => 10,
        "NORMAL" => 11,
        "FTEST_NONC" => 12,
        "CHISQ_NONC" => 13,
        "TTEST_NONC" => 17,
        "LOGISTIC" => 14,
        "LAPLACE" => 15,
        "UNIFORM" => 16,
        "WEIBULL" => 18,
        "CHI" => 19,
        "INVGAUSS" => 20,
        "EXTVAL" => 21,
        other => panic!("unknown code {other}"),
    }
}

/// Which AFNI operation a fixture line performs.
#[derive(Debug, PartialEq)]
enum Op {
    /// `P(X <= val)`.
    Cdf,
    /// `P(X > val)`.
    Upper,
    /// `x` with `P(X <= x) = val`.
    Inverse,
}

struct Parsed {
    op: Op,
    value: f64,
    spec: StatSpec,
    discrete: bool,
}

fn parse(args: &[String]) -> Parsed {
    let (op, rest) = match args[0].as_str() {
        "-q" => (Op::Upper, &args[1..]),
        "-1" => (Op::Inverse, &args[1..]),
        _ => (Op::Cdf, args),
    };
    let value: f64 = rest[0].parse().unwrap();
    let code = code_for(&rest[1]);
    let mut p = [0.0; 3];
    for (slot, text) in p.iter_mut().zip(&rest[2..]) {
        *slot = text.parse().unwrap();
    }
    // The fixture uses NIfTI parameters, so CORREL carries a single dof.
    let spec = StatSpec::from_intent(code, p, IntentOrigin::Standard)
        .unwrap()
        .unwrap();
    Parsed {
        op,
        value,
        discrete: matches!(spec.kind, StatKind::Binom | StatKind::Poisson),
        spec,
    }
}

/// Relative tolerance for CDFLIB-derived reference values.
const TOL: Tolerance = Tolerance {
    abs: 1e-300,
    rel: 1e-8,
};

/// Probabilities this small are at the edge of what CDFLIB resolves; compare
/// them in log space instead.
const TINY: f64 = 1e-290;

/// AFNI's CDFLIB `cumchn` and `cumfnc` (noncentral chi-square and F) stop their
/// series at an internal tolerance of about 1e-5, and the printed tails are
/// differences of such sums, so they are only good to ~1e-5 ABSOLUTE (worst observed 1e-5; e.g. for
/// `F(3,20; 2)` at 3 AFNI gives 0.8237480 where an independent summation and
/// afni-core both give 0.8237555); they are
/// the less accurate side of this comparison. (Noncentral t agrees to ~2e-10 and
/// uses the ordinary tolerance.) The exact values are cross-checked independently
/// in `stats::tests`.
const CDFLIB_NONCENTRAL_TOL: Tolerance = Tolerance {
    abs: 2e-5,
    rel: 1e-6,
};

/// The CDFLIB-limited noncentral kinds.
fn is_cdflib_noncentral(kind: StatKind) -> bool {
    matches!(kind, StatKind::FtestNonc | StatKind::ChisqNonc)
}

